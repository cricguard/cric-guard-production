import json
import warnings
from pathlib import Path
from typing import Any

import joblib
from sklearn.exceptions import InconsistentVersionWarning

BASE_DIR = Path(__file__).resolve().parent.parent
MODELS_DIR = BASE_DIR / "models"
MODEL_PATH = MODELS_DIR / "random_forest_v2_57feat.pkl"
SCHEMA_PATH = MODELS_DIR / "feature_schema.json"
IMPUTATION_PATH = MODELS_DIR / "imputation_metadata.json"


def _require_file(path: Path, description: str) -> Path:
    if not path.exists():
        raise FileNotFoundError(f"Missing required {description}: {path}")
    return path


def load_feature_schema() -> list[str]:
    """Load the ordered feature list used by the production model."""
    schema_file = _require_file(SCHEMA_PATH, "feature schema")
    with schema_file.open("r", encoding="utf-8") as f:
        payload = json.load(f)

    if not isinstance(payload, dict) or "feature_order" not in payload:
        raise ValueError(f"Feature schema at {schema_file} is invalid or missing 'feature_order'.")

    feature_order = payload["feature_order"]
    if not isinstance(feature_order, list) or not feature_order:
        raise ValueError(f"Feature schema at {schema_file} is empty or malformed.")

    return feature_order


def load_imputation_metadata() -> dict[str, float]:
    """Load the approved imputation median values used for biomechanical features."""
    imputation_file = _require_file(IMPUTATION_PATH, "imputation metadata")
    with imputation_file.open("r", encoding="utf-8") as f:
        metadata = json.load(f)

    if not isinstance(metadata, dict):
        raise ValueError(f"Imputation metadata at {imputation_file} must be a JSON object.")

    expected_keys = {
        "left_knee_angle",
        "right_knee_angle",
        "trunk_inclination_angle",
        "shoulder_hip_alignment_angle",
        "left_elbow_angle",
        "right_elbow_angle",
    }
    missing_keys = sorted(expected_keys - set(metadata.keys()))
    if missing_keys:
        raise ValueError(
            f"Imputation metadata at {imputation_file} is missing required keys: {missing_keys}"
        )

    return metadata


def load_model() -> Any:
    """
    Load the serialized Random Forest model from a trusted source only.

    This project assumes the artifact is generated by its own training pipeline and is
    therefore trusted. The loader fails fast if the file is missing or if the model's
    expected feature count/order does not match the feature builder.
    """
    model_file = _require_file(MODEL_PATH, "trained model artifact")

    if model_file.suffix.lower() not in {".pkl", ".joblib"}:
        raise ValueError(f"Model artifact {model_file} must be a pickle/joblib file.")

    try:
        with warnings.catch_warnings():
            warnings.simplefilter("error", InconsistentVersionWarning)
            model = joblib.load(model_file)
    except InconsistentVersionWarning as exc:
        raise RuntimeError(
            "Model artifact is incompatible with the installed scikit-learn version. "
            f"Please retrain the model or install the matching sklearn version for {model_file}."
        ) from exc
    except Exception as exc:  # pragma: no cover - defensive path for startup validation
        raise RuntimeError(
            f"Failed to load model artifact from {model_file}. The file may be corrupted or incompatible."
        ) from exc

    if not hasattr(model, "predict"):
        raise TypeError(f"Artifact at {model_file} does not appear to be a valid sklearn-compatible model.")

    feature_order = load_feature_schema()
    expected_count = len(feature_order)

    if hasattr(model, "n_features_in_") and model.n_features_in_ != expected_count:
        raise ValueError(
            "Model feature count mismatch: model expects "
            f"{model.n_features_in_} features but feature builder produces {expected_count}."
        )

    if hasattr(model, "feature_names_in_"):
        model_feature_names = list(model.feature_names_in_)
        if model_feature_names != feature_order:
            raise ValueError(
                "Model feature order mismatch: model expects "
                f"{model_feature_names} but feature builder emits {feature_order}."
            )

    return model


FEATURE_SCHEMA = load_feature_schema()
TRAINING_MEDIANS = load_imputation_metadata()
